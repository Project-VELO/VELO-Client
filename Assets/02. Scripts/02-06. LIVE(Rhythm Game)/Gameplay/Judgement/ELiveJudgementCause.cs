/// <summary>
/// 판정이 어떤 경로로 확정되었는지입니다. 같은 BAD라도 이르게 눌렀는지, 아예 치지 않았는지, 롱노트를 일찍 뗐는지에 따라
/// 채보에서 의심할 곳이 다르므로, 판정 등급과 따로 전달합니다.
/// </summary>
public enum ELiveJudgementCause
{
    /// <summary>
    /// 입력 타이밍으로 판정되었습니다. 이르게 눌러 소비된 BAD와 끝까지 유지한 롱노트도 여기에 속합니다.
    /// </summary>
    INPUT,

    /// <summary>
    /// 입력 없이 유효 입력 시간이 지났거나, 완주 시점까지 처리되지 않았습니다. 오차 값이 없습니다.
    /// </summary>
    MISS,

    /// <summary>
    /// 롱노트를 눌렀지만 끝까지 유지하지 못했습니다. 오차 값은 누른 순간의 것입니다.
    /// </summary>
    HOLD_BREAK,
}
