/// <summary>
/// 스케줄 행이 화면에 보여 줄 상태입니다.
///
/// 세이브의 EScheduleStatus와 다릅니다. 저장되는 것은 완료 여부뿐이고, 잠김은 그 행이 오늘 것인지
/// 내일 예고인지에 따라 화면에서만 갈립니다. 두 개념을 한 열거형으로 합치면 저장되지 않는 값이
/// 세이브 열거형에 섞여 직렬화 순서를 건드리게 됩니다.
///
/// 오늘의 세 스케줄은 순서 없이 모두 처음부터 진행할 수 있으므로(기획서 3-E-2-2),
/// LOCKED가 되는 것은 아직 오지 않은 날짜의 예고 행뿐입니다.
/// </summary>
public enum EScheduleViewState
{
    /// <summary>
    /// 아직 진행할 수 없는 상태입니다. 내일 예고 행이 여기에 해당합니다.
    /// </summary>
    LOCKED,

    /// <summary>
    /// 지금 진행할 수 있는 상태입니다. 바로가기가 열려 있습니다.
    /// </summary>
    AVAILABLE,

    COMPLETED
}
