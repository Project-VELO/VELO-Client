/// <summary>
/// 화면 연출 한 가지가 무엇을 하는지입니다(연출표의 [화면 이펙트] 열).
///
/// 연출표에는 169가지 이펙트 ID가 등장하지만, 실제로 화면이 하는 일은 몇 가지로 수렴합니다.
/// "화면 크게 덜컹거림"과 "화면 미세하게 진동"은 진폭만 다른 같은 동작입니다.
/// 그래서 ID마다 클래스를 만들지 않고, 종류 몇 개에 세기를 실어 effects.json이 조합을 정합니다.
///
/// 스토리 캔버스가 Screen Space - Overlay라 URP 포스트 프로세싱이 걸리지 않습니다.
/// 블룸·글리치·색보정을 진짜로 쓰려면 캔버스를 카메라 방식으로 바꿔야 하므로,
/// 여기서는 전체화면 덮개 이미지와 RectTransform 조작으로 낼 수 있는 것만 다룹니다.
///
/// 대사 JSON과의 호환을 위해 새 값은 맨 뒤에만 추가합니다.
/// </summary>
public enum EStoryEffectKind
{
    /// <summary>
    /// 아무것도 하지 않습니다. 아트나 별도 시스템이 있어야 하는 연출이 여기로 떨어집니다.
    /// 값을 적지 않은 줄도 여기로 옵니다.
    /// </summary>
    NONE,

    /// <summary>
    /// 무대를 흔듭니다. 연출표의 "덜컹거림"·"진동"·"흔들림"이 모두 이쪽입니다.
    /// </summary>
    SHAKE,

    /// <summary>
    /// 무대를 확대하거나 축소합니다.
    /// </summary>
    ZOOM,

    /// <summary>
    /// 무대를 밀어 시점을 옮깁니다. 연출표의 "시점 이동(Pan)"·"틸트"·"클로즈업"이 이쪽입니다.
    /// </summary>
    PAN,

    /// <summary>
    /// 덮개 색을 목표값까지 서서히 바꾸고 그대로 둡니다.
    /// 암전·화이트아웃·명암 조절·색 필터·비네팅이 모두 이 하나로 표현됩니다.
    /// </summary>
    TINT,

    /// <summary>
    /// 덮개를 한 번 확 올렸다가 원래대로 되돌립니다. 섬광·점멸·컷 전환에 씁니다.
    /// TINT와 달리 끝나면 흔적이 남지 않습니다.
    /// </summary>
    FLASH,

    /// <summary>
    /// 진행 중인 연출을 멈추고 무대를 제자리로 돌립니다.
    /// 연출표의 "흔들림 멈춤"·"줌인 해제"·"화면 멈춤"이 이쪽입니다.
    /// </summary>
    STOP
}
