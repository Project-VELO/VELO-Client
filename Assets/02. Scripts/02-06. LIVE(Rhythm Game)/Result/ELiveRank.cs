/// <summary>
/// 라이브 플레이 결과에 따라 부여되는 정확도 기반 랭크입니다.
///
/// 선언 순서가 곧 우열입니다. 좋은 랭크일수록 정수 값이 작으므로,
/// "B랭크 이상" 같은 최소 조건 비교는 rank &lt;= ELiveRank.B 형태가 됩니다(부등호 방향 주의).
///
/// 이 값은 세이브의 최고 기록에 저장되며 JsonUtility가 정수로 직렬화하므로,
/// 값의 순서를 바꾸거나 중간에 끼워 넣지 않습니다.
/// </summary>
public enum ELiveRank
{
    /// <summary>
    /// 정확도 100% 달성 및 모든 노트 PERFECT 판정인 경우입니다.
    /// </summary>
    PERFECT_S,

    /// <summary>
    /// 정확도 97.00% 이상인 경우입니다.
    /// </summary>
    S,

    /// <summary>
    /// 정확도 95.00% 이상 97.00% 미만인 경우입니다.
    /// </summary>
    A,

    /// <summary>
    /// 정확도 85.00% 이상 95.00% 미만인 경우입니다.
    /// </summary>
    B,

    /// <summary>
    /// 정확도 70.00% 이상 85.00% 미만인 경우입니다.
    /// </summary>
    C,

    /// <summary>
    /// 정확도 70.00% 미만이거나, 귀신 노트 실수(BAD/오입력)가 발생한 경우입니다.
    /// </summary>
    FAILED
}
