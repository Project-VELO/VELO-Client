/// <summary>
/// 주차 스케줄 표에서 날짜 한 칸이 가질 수 있는 화면 상태입니다(기획서 3-E-3-1).
///
/// 세이브에 저장하지 않고 현재 날짜와 완료 기록으로부터 매번 계산합니다.
/// 저장해 두면 현재 날짜와 어긋날 수 있고, 홈과 사무실이 서로 다른 상태를 보여줄 여지가 생깁니다.
/// </summary>
public enum EDayViewState
{
    /// <summary>
    /// 아직 진행할 수 없는 이후 날짜입니다. 비활성으로 표시하고 클릭을 받지 않습니다.
    /// </summary>
    LOCKED,

    /// <summary>
    /// 현재 진행 중인 날짜입니다. 외곽 테두리를 강조하되, 일일 스케줄이 남아 있어 클릭할 수 없습니다.
    /// </summary>
    IN_PROGRESS,

    /// <summary>
    /// 오늘의 필수 스케줄을 모두 마쳐 하루 마무리를 할 수 있는 상태입니다.
    /// 하이라이트를 유지한 채 점멸 등 추가 강조를 넣고 클릭을 허용합니다.
    /// </summary>
    COMPLETABLE,

    /// <summary>
    /// 하루 마무리까지 마친 이전 날짜입니다. 완료 표시를 남기고 클릭을 받지 않습니다.
    /// </summary>
    COMPLETED
}
