/// <summary>
/// 대사 한 줄의 출력 속도이자 방식입니다(연출표의 [속도] 열).
///
/// 속도 배수만으로는 "단어 단위 툭툭"을 표현할 수 없어 방식까지 함께 담습니다.
/// 실제 초 단위 값과 각 단계의 쓰임새는 StoryTypingSpeed의 기준표가 정합니다.
///
/// 대사 JSON은 이름 문자열로 주고받으므로(MasterDataEnum) 선언 순서는 데이터와 무관합니다.
/// 다만 없는 이름은 경고와 함께 NORMAL로 떨어지므로, 값을 지울 때는 대본을 함께 고쳐야 합니다.
/// </summary>
public enum ETextSpeed
{
    /// <summary>
    /// 기준 속도입니다. 값을 적지 않은 줄이 여기로 떨어집니다.
    /// 일상 대화와 평범한 상황 설명에 씁니다.
    /// </summary>
    NORMAL,

    /// <summary>
    /// 무거운 독백이나 심각한 결정처럼, 한 글자씩 씹어 읽게 만들어야 하는 줄에 씁니다.
    /// </summary>
    SLOW,

    /// <summary>
    /// 느리게보다 더 느립니다. 한 문장이 통째로 무게를 갖는 자리에 씁니다.
    ///
    /// 회차를 닫는 마지막 지문이나, 초월적 존재가 처음 말을 거는 줄이 여기 옵니다.
    /// 느리게와 나눈 것은 두 속도가 같은 화면에 이어 나올 때 차이가 들리기 때문입니다.
    /// </summary>
    VERY_SLOW,

    /// <summary>
    /// 다급하게 몰아치는 줄에 씁니다. 즉시와 달리 타이핑은 보이되 보통보다 빠르게 지나갑니다.
    /// 비명을 지르며 달려가거나, 같은 일이 정신없이 되풀이되는 장면에 씁니다.
    /// </summary>
    FAST,

    /// <summary>
    /// 타이핑 없이 한 번에 전부 출력합니다. 시스템 메시지나, 당황해서 말을 쏟아내는 대사에 씁니다.
    /// </summary>
    INSTANT,

    /// <summary>
    /// 글자를 하나씩 찍지 않고 문장 전체를 서서히 드러냅니다.
    ///
    /// 타이핑이 "누가 말하고 있다"는 인상을 주는 것과 달리, 이쪽은 글자가 저절로 배어 나오는
    /// 인상을 줍니다. 10화 마지막 초대장처럼 사람이 아니라 화면이 말을 거는 자리에 씁니다.
    /// </summary>
    FADE_IN,

    /// <summary>
    /// 글자가 아니라 단어 단위로 끊어서 출력합니다.
    /// 또박또박 화를 내거나, 초월적 존재가 압박감을 주며 경고할 때 씁니다.
    /// </summary>
    WORD_BY_WORD
}
