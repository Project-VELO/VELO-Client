/// <summary>
/// 인물이 자기 자리에 나타나고 사라지는 방식입니다(연출표의 [캐릭터 연출]).
///
/// 대사 JSON은 이름 문자열로 주고받으므로(MasterDataEnum) 선언 순서는 데이터와 무관합니다.
/// 없는 이름은 경고와 함께 FADE로 떨어지므로, 값을 지울 때는 대본을 함께 고쳐야 합니다.
/// </summary>
public enum EStoryCharacterTransition
{
    /// <summary>
    /// 서서히 나타나고 서서히 사라집니다. 값을 적지 않은 줄이 여기로 떨어집니다.
    /// 장면이 조용히 이어지는 대부분의 자리에 씁니다.
    /// </summary>
    FADE,

    /// <summary>
    /// 튀어나오듯 한 번에 나타납니다. 크기가 살짝 커졌다 제자리로 돌아옵니다.
    /// 놀라서 소리치거나 갑자기 끼어드는 줄에 씁니다.
    /// </summary>
    POPUP,

    /// <summary>
    /// 자기 자리 바깥에서 미끄러져 들어오고, 나갈 때도 같은 쪽으로 빠집니다.
    /// 걸어 들어오거나 지나가는 인물에 씁니다.
    /// </summary>
    SLIDE,

    /// <summary>
    /// 위에서 아래로 내려옵니다. 허공을 떠다니다 얼굴 앞까지 다가오는 인물에 씁니다.
    /// </summary>
    DROP,

    /// <summary>
    /// 연출 없이 그 자리에서 즉시 나타나고 즉시 사라집니다.
    /// 컷이 바뀌듯 끊어야 하는 자리에 씁니다.
    /// </summary>
    CUT
}
