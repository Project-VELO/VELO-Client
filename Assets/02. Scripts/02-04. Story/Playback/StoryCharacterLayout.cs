using System;
using UnityEngine;

/// <summary>
/// 감상 화면에서 인물 한 명을 어떻게 세울지 정하는 값입니다.
///
/// 그림마다 인물이 차지하는 비율이 달라 한 크기로 묶을 수 없습니다.
/// 일러스트가 있는 인물은 화면 높이에 맞춰 세우지만, 실루엣만 있는 인물이나
/// 사람이 아닌 인물은 그보다 작고 끝에서 얼마쯤 띄워야 화면에 어울립니다.
/// </summary>
[Serializable]
public struct StoryCharacterLayout
{
    /// <summary>
    /// 화면에 그릴 높이입니다. 0이면 감상 화면의 높이에 맞춥니다.
    /// 너비는 원본 비율에서 계산하므로 따로 적지 않습니다.
    ///
    /// 너비가 아니라 높이로 잡는 이유는, 같은 인물이라도 표정마다 그림의 원본 비율이
    /// 다르기 때문입니다. 지우는 Normal이 1200x970인데 나머지 넷은 2000x3000입니다.
    /// 너비를 1200으로 묶으면 앞은 970px, 뒤는 1800px 높이가 되어 화면 밖으로 나갑니다.
    /// 인물은 바닥을 딛고 서므로 높이를 맞추는 편이 어느 그림이 와도 발이 제자리에 옵니다.
    /// </summary>
    [Min(0)]
    public int Height;

    /// <summary>
    /// 자기가 선 쪽 화면 끝에서 띄우는 거리입니다. 가운데 자리에는 쓰이지 않습니다.
    /// </summary>
    [Min(0)]
    public int EdgeOffset;
}
